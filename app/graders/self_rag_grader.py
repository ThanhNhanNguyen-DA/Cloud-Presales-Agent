"""
Self-RAG Grounding Grader (Phase 8) — Hallucination check.

Runs AFTER a sub-agent (Calculator/Document/Competitor) produces a response and
BEFORE it is returned to the user. Uses a separate LLM call (decoupled from the
agent that generated the answer) to verify the answer against the raw tool/RAG output:
numbers (cost, time, vCPU, RAM, IOPS, storage), service names, and SLA / compliance terms.

Flow (bounded to one retry):
  FAIL #1 -> `grader_feedback` = the issues found, `retry_count` = 1 -> the graph re-runs the
             SAME agent, which sees the feedback (app/agents/tool_agent.py).
  FAIL #2 -> the answer is delivered with a clear warning appended (never silently wrong).
  The grader itself failing (LLM down / rate-limited) or answering unparseably is treated as
  "could not verify": no retry, the answer gets the warning.
"""

from __future__ import annotations

import json
import logging
import re

from app.graph.state import GraphState
from app.llm import get_chat_llm

logger = logging.getLogger(__name__)

grader_llm = get_chat_llm(temperature=0, role="grader")

MAX_GRADING_ATTEMPTS = 2  # first answer + one retry

GROUNDING_GRADER_PROMPT = """You are the Grounding Grader, a quality-control check for the Presales Cloud system.
Task: verify that the FINAL ANSWER is supported by the RAW DATA returned by the tool / document search.

USER QUESTION:
{question}

RAW DATA (tool calls with their arguments and results, database rows or RAG documents):
{raw_output}

FINAL ANSWER (generated by the Agent to send to the user):
{final_answer}

Check:
1. Every number in the FINAL ANSWER (cost, time, vCPU, RAM, IOPS, storage size, SLA %, credits)
   matches the RAW DATA. Formatting differences are fine (e.g. "0.28 h" vs "0.28 hours",
   "16.7 minutes" vs "16,7 phút"); a different value is not.
2. Service names, certifications and SLA / compliance terms in the FINAL ANSWER appear in the
   RAW DATA (the answer must not invent a service, a certification or a guarantee).
3. Values the user gave in the USER QUESTION (or that appear as tool arguments) may be
   repeated in the answer — they are inputs, not claims to verify.
4. Explanations, wording, unit labels and general caveats that add no new facts are fine.
If the RAW DATA contains an "error" and the answer explains that error without inventing a figure, PASS.

Reply with ONLY a JSON object, no other text:
{{"verdict": "PASS" or "FAIL", "issues": ["<short description of each mismatch>"]}}"""

GRADING_WARNING = (
    "\n\n⚠️ Note: The system detected a possible discrepancy between this answer and the "
    "source data. Please double-check with the Calculator/Tool before sending this to the customer."
)
UNVERIFIED_WARNING = (
    "\n\n⚠️ Note: The automatic fact check could not run for this answer. "
    "Please double-check the figures before sending this to the customer."
)

_VERDICT_WORD = re.compile(r"\b(PASS|FAIL)\b")


def parse_verdict(text: str) -> tuple[bool | None, list[str]]:
    """
    Parse the grader's reply into (passed, issues).

    Accepts the requested JSON object (also inside a ```json fence or surrounded by text),
    or — as a fallback — a bare PASS/FAIL word. If both words appear without JSON, FAIL wins
    (the safe side). Returns (None, []) when no verdict can be found.
    """
    text = (text or "").strip()
    match = re.search(r"\{.*\}", text, re.DOTALL)
    if match:
        try:
            data = json.loads(match.group())
            verdict = str(data.get("verdict", "")).strip().upper()
            issues = [str(i) for i in data.get("issues") or [] if str(i).strip()]
            if verdict in {"PASS", "FAIL"}:
                return verdict == "PASS", issues
        except (json.JSONDecodeError, AttributeError):
            pass
    words = set(_VERDICT_WORD.findall(text.upper()))
    if "FAIL" in words:
        return False, []
    if "PASS" in words:
        return True, []
    return None, []


def grounding_grader_node(state: GraphState) -> dict:
    """
    Grounding Grader node. Returns only the state keys it changes (a LangGraph partial update).

    - No raw tool/RAG data to cross-check (e.g. the agent asked a clarifying question
      instead of calling a tool) -> auto-PASS.
    - Otherwise a decoupled LLM compares `final_response` with `raw_tool_output`.
    - PASS clears `grader_feedback`. A first FAIL stores the issues in `grader_feedback` and
      bumps `retry_count` so builder.py re-runs the same agent. A FAIL on the last attempt
      appends a warning to `final_response` (never leaving it empty).
    """
    raw_output = state.get("raw_tool_output") or ""
    final_answer = state.get("final_response") or ""
    retry_count = state.get("retry_count") or 0

    if not raw_output.strip():
        return {"grading_passed": True, "grader_feedback": None}

    prompt = GROUNDING_GRADER_PROMPT.format(
        question=state.get("user_query") or "", raw_output=raw_output, final_answer=final_answer
    )
    try:
        reply = grader_llm.invoke(prompt)
        content = reply.content if isinstance(reply.content, str) else str(reply.content)
        passed, issues = parse_verdict(content)
    except Exception as exc:  # noqa: BLE001 - the grader must never take the answer down
        logger.warning("Grading failed: %s", exc)
        passed, issues = None, []

    if passed is None:
        # Could not verify: don't loop, deliver the answer with an explicit caveat.
        logger.info("verdict=UNVERIFIED attempt=%d", retry_count + 1)
        return {
            "grading_passed": False,
            "grader_feedback": None,
            "retry_count": MAX_GRADING_ATTEMPTS,
            "final_response": final_answer + UNVERIFIED_WARNING,
        }

    logger.info("verdict=%s attempt=%d issues=%d", "PASS" if passed else "FAIL",
                retry_count + 1, len(issues))
    if passed:
        return {"grading_passed": True, "grader_feedback": None}

    attempts = retry_count + 1
    if attempts >= MAX_GRADING_ATTEMPTS:
        return {
            "grading_passed": False,
            "retry_count": attempts,
            "grader_feedback": None,
            "final_response": final_answer + GRADING_WARNING,
        }
    return {
        "grading_passed": False,
        "retry_count": attempts,
        "grader_feedback": "\n".join(f"- {i}" for i in issues)
        or "- At least one figure, service name or term does not match the tool data.",
    }
