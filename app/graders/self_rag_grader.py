"""
Self-RAG Grounding Grader (Phase 8) — Hallucination check.

Runs AFTER a sub-agent (Calculator/Document/Competitor) produces a response and
BEFORE it is returned to the user. Uses a separate LLM call (decoupled from the
agent that generated the answer) to verify that the numbers in the final answer
match the raw tool/RAG output, catching numerical hallucinations.
"""

from app.llm import get_chat_llm
from app.graph.state import GraphState


grader_llm = get_chat_llm(temperature=0)

GROUNDING_GRADER_PROMPT = """You are the Grounding Grader, a quality-control check for the Presales Cloud system.
Task: verify whether the FINAL ANSWER matches the RAW DATA from the tool/document, especially numbers
(cost, time, vCPU, RAM, IOPS, storage size).

RAW DATA (from the calculation tool or RAG document):
{raw_output}

FINAL ANSWER (generated by the Agent to send to the user):
{final_answer}

Check: do the numbers in the FINAL ANSWER exactly match the RAW DATA?
If the RAW DATA is empty or contains no numbers (e.g. a general question that didn't need a tool), treat it as PASS.

Return EXACTLY one word: "PASS" if it fully matches, or "FAIL" if there is any numerical mismatch."""

GRADING_WARNING = (
    "\n\n⚠️ Note: The system detected a possible numerical discrepancy in this answer. "
    "Please double-check with the Calculator/Tool before sending this to the customer."
)


def grounding_grader_node(state: GraphState) -> GraphState:
    """
    Grounding Grader node.

    - If there is no raw tool/RAG data to cross-check against (e.g. the "general"
      route, or an agent that didn't call any tool), auto-PASS.
    - Otherwise ask a decoupled LLM whether the numbers in `final_response` match
      `raw_tool_output`, and set `grading_passed` accordingly.
    - Bounds the retry loop: on the first failure it bumps `retry_count` so the
      graph re-routes once. If it still FAILS after the retry budget is used, it
      appends a clear warning to `final_response` (never leaving it empty) so the
      user is alerted instead of silently trusting a possibly-wrong number.
    """
    raw_output = state.get("raw_tool_output") or ""
    final_answer = state.get("final_response") or ""
    retry_count = state.get("retry_count") or 0

    if not raw_output.strip():
        # No raw data to cross-check against -> auto pass.
        state["grading_passed"] = True
        return state

    prompt = GROUNDING_GRADER_PROMPT.format(raw_output=raw_output, final_answer=final_answer)
    grading_result = grader_llm.invoke(prompt).content.strip().upper()
    passed = "PASS" in grading_result
    state["grading_passed"] = passed

    if not passed:
        if retry_count >= 1:
            # Retry budget already used -> give up, but never return an empty answer;
            # attach a clear warning so the Presales staff double-checks the numbers.
            state["final_response"] = final_answer + GRADING_WARNING
        # Count this failure so the bounded retry in builder.py can converge.
        state["retry_count"] = retry_count + 1

    return state
